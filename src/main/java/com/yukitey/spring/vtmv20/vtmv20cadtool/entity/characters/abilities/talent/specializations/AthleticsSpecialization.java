package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.talent.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для таланта Атлетика (Athletics).
 * Атлетика охватывает общую физическую подготовку, координацию и владение телом.
 * Данные специализации дают бонус при совершении сложных физических маневров.
 */
@Getter
@AllArgsConstructor
public enum AthleticsSpecialization implements EnumSpecialization {

    /**
     * Плавание (Swimming).
     * Мастерство перемещения в водной среде.
     */
    ABL_TAL_ATH_SWIMMING(
            "Плавание",
            "Ваше тело идеально приспособлено к водной среде. Применяется для преодоления водных преград, затяжных заплывов или спасения тонущих."),

    /**
     * Альпинизм (Climbing).
     * Навык вертикального перемещения по сложным поверхностям.
     */
    ABL_TAL_ATH_CLIMBING(
            "Альпинизм",
            "Вы мастерски находите зацепы и точки опоры. Применяется при подъеме по скалам, отвесным стенам зданий, деревьям и другим вертикальным препятствиям."),

    /**
     * Акробатика (Acrobatics).
     * Безупречное чувство баланса и контроль тела в динамике.
     */
    ABL_TAL_ATH_ACROBATICS(
            "Акробатика",
            "Вы мастерски владеете своим телом в воздухе и на узких опорах. Применяется при выполнении кувырков, сальто, сохранении равновесия и сложных гимнастических элементах."),

    /**
     * Танцы (Dancing).
     * Ритмичность, гибкость и артистизм движений.
     */
    ABL_TAL_ATH_DANCING(
            "Танцы",
            "Ваши движения текучи и ритмичны. Применяется в искусстве танца любого стиля, а также в ситуациях, требующих изящной координации и контроля темпа движений."),

    /**
     * Паркур (Parkour).
     * Искусство эффективного и скоростного преодоления городских препятствий.
     */
    ABL_TAL_ATH_PARKOUR(
            "Паркур",
            "Весь город — ваша игровая площадка. Применяется при скоростном перемещении по пересеченной городской местности, прыжках между зданиями и эффективном преодолении заграждений.");

    /** Локализованное название специализации для отображения. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения специализации. */
    private final String description;
}