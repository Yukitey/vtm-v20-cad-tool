package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.talent.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для таланта Драка (Brawl).
 * Отражают мастерство персонажа в рукопашном бою без применения холодного или огнестрельного оружия.
 */
@Getter
@AllArgsConstructor
public enum BrawlSpecialization implements EnumSpecialization {

    /**
     * Грязные приемы (Dirty Fighting).
     * Отсутствие моральных ограничений в бою.
     */
    ABL_TAL_BRW_DIRTY_FIGHTING(
            "Грязные приемы",
            "Для вас не существует правил честного боя. Применяется при использовании ударов в уязвимые места, ослепления противника подручными средствами и других подлых уловок."),

    /**
     * Удары (Striking).
     * Мастерство нанесения точных и мощных атак конечностями.
     */
    ABL_TAL_BRW_STRIKING(
            "Удары",
            "Ваши кулаки, локти и колени работают как отлаженный механизм. Применяется при нанесении прямых ударов и любых серий атак, направленных на физическое сокрушение оппонента."),

    /**
     * Броски (Throws).
     * Умение использовать инерцию противника против него самого.
     */
    ABL_TAL_BRW_THROWS(
            "Броски",
            "Вы знаете, как опрокинуть врага на землю. Применяется при выполнении подножек, перебрасывании через бедро или плечо, а также при защитных маневрах с контратакой."),

    /**
     * Захваты (Grappling).
     * Контроль противника на максимально близкой дистанции.
     */
    ABL_TAL_BRW_GRAPPLING(
            "Захваты",
            "Вы — мастер борьбы в клинче. Применяется при попытках схватить, удержать, обездвижить противника или провести удушающий прием.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения специализации. */
    private final String description;
}
