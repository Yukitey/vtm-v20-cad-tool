package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.characteristics.social.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для характеристики Привлекательность (Appearance).
 * Отражают физическую красоту персонажа и его способность производить визуальное впечатление.
 */
@Getter
@AllArgsConstructor
public enum AppearanceSpecialization implements EnumSpecialization {

    /**
     * Экзотичность (Exotic).
     * Необычная, редкая красота, которая приковывает взгляды своей новизной.
     */
    APP_EXOTIC(
            "Экзотичность",
            "Ваша внешность необычна и притягательна. Применяется, когда ваша инаковость помогает выделиться из толпы или заворожить тех, кто не привык к подобным чертам."),

    /**
     * Фотогеничность (Photogenic).
     * Способность идеально выглядеть на любых изображениях.
     */
    APP_PHOTOGENIC(
            "Фотогеничность",
            "Вы всегда получаетесь великолепно. Применяется при съемках, видеозаписи или когда нужно оставить безупречный визуальный след в цифровой или печатной среде."),

    /**
     * Чувство стиля (Stylish).
     * Умение подчеркнуть свои достоинства через одежду и манеры.
     */
    APP_STYLISH(
            "Чувство стиля",
            "Вы — икона моды. Применяется, когда ваш безупречный вкус в одежде и аксессуарах должен подчеркнуть ваш статус или помочь влиться в высшее общество."),

    /**
     * Потрясающая внешность (Stunning).
     * Красота настолько ослепительная, что она буквально лишает дара речи.
     */
    APP_STUNNING(
            "Потрясающая внешность",
            "Ваша красота ошеломляет. Применяется в моменты первого знакомства или выступлений, когда визуальное воздействие должно на мгновение обезоружить оппонента."),

    /**
     * Запоминающийся образ (Haunting).
     * Красота, которая оставляет глубокий, почти мистический след в памяти.
     */
    APP_HAUNTING(
            "Запоминающийся образ",
            "Вас невозможно забыть. Применяется, когда вы хотите, чтобы ваш образ преследовал мысли свидетеля еще долгое время после того, как вы покинули комнату.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения. */
    private final String description;
}