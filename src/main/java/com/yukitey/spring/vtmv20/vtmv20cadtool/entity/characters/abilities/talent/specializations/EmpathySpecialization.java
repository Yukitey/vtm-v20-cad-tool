package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.talent.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для таланта Эмпатия (Empathy).
 * Отражают мастерство персонажа в понимании чужих чувств, выявлении скрытых мотивов
 * и его способность сопереживать окружающим для установления доверительного контакта.
 */
@Getter
@AllArgsConstructor
public enum EmpathySpecialization implements EnumSpecialization {

    /**
     * Эмоции (Emotions).
     * Способность точно определять текущее эмоциональное состояние другого существа.
     */
    ABL_TAL_EMP_EMOTIONS(
            "Эмоции",
            "Вы читаете чувства людей как открытую книгу. Применяется для определения страха, гнева, радости или печали собеседника, даже если он пытается их скрыть."),

    /**
     * Проницательность (Insight).
     * Умение видеть то, что стоит за словами и жестами оппонента.
     */
    ABL_TAL_EMP_INSIGHT(
            "Проницательность",
            "Вы чувствуете малейшую фальшь в поведении. Применяется для распознавания лжи, скрытого напряжения или когда нужно понять, что человек на самом деле думает о ситуации."),

    /**
     * Мотивы (Motives).
     * Понимание внутренних причин, побуждающих человека к действиям.
     */
    ABL_TAL_EMP_MOTIVES(
            "Мотивы",
            "Вы понимаете, чего люди хотят на самом деле. Применяется для выявления скрытых целей, амбиций или страхов, которые управляют поступками окружающих."),

    /**
     * Завоевание доверия (Gaining Trust).
     * Талант располагать людей к себе, создавая атмосферу безопасности и понимания.
     */
    ABL_TAL_EMP_TRUST(
            "Завоевание доверия",
            "Люди инстинктивно хотят открыться вам. Применяется для того, чтобы разговорить замкнутого человека, успокоить напуганного или быстро установить глубокую эмоциональную связь.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения специализации. */
    private final String description;
}