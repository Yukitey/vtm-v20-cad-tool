package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.enlightenment.paths;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.virtue.ConscienceOrConviction;
import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.virtue.SelfControlOrInstinct;

import java.util.List;

/**
 * Интерфейс Пути Просветления (Enlightenment Path).
 * <p>
 * Путь Просветления — это моральный и философский кодекс,
 * которому следует вампир, отказавшийся от Человечности.
 * Каждый путь определяет, какие поступки считаются греховными,
 * какие добродетели его поддерживают, и какова его этическая структура.
 * <p>
 * В V20 существует множество путей: Человечность (не считается путём,
 * но является базовым моральным компасом), Путь Каина, Путь Зверя,
 * Путь Крови и другие.
 * <p>
 * См. главу 7 «Мораль» в книге правил V20.
 */
public interface EnlightenmentPath {
    /**
     * Уникальный строковый идентификатор пути.
     * <p>
     * Используется для хранения в базе данных и для получения
     * конкретной реализации через фабрику или реестр.
     *
     * @return уникальный идентификатор, например "HUMANITY", "PATH_OF_CAINE"
     */
    String getId();

    /**
     * Отображаемое имя пути для пользовательского интерфейса.
     * <p>
     * Например: "Человечность (Humanity)", "Путь Каина (Path of Caine)"
     *
     * @return человекочитаемое название пути
     */
    String getDisplayName();

    /**
     * Столп (Pillar) пути — основная философская идея,
     * на которой строится этика.
     * <p>
     * Например, для Человечности столп — "Нормальность",
     * для Пути Каина — "Вера".
     *
     * @return описание столпа пути
     */
    String getPillar();

    /**
     * Полное описание пути, его философия и основные принципы.
     *
     * @return развёрнутое описание пути
     */
    String getDescription();

    /**
     * Определяет, какая добродетель из пары Совесть/Решимость
     * используется для этого пути.
     * <p>
     * - Совесть (Conscience) — для Пути Человечности
     * - Решимость (Conviction) — для большинства альтернативных путей
     *
     * @return тип добродетели (CONSCIENCE или CONVICTION)
     */
    ConscienceOrConviction getMoralityChoice();

    /**
     * Определяет, какая добродетель из пары Самообладание/Инстинкты
     * используется для этого пути.
     * <p>
     * - Самообладание (Self-Control) — для контроля Зверя
     * - Инстинкты (Instinct) — для принятия и направления Зверя
     *
     * @return тип добродетели (SELF_CONTROL или INSTINCT)
     */
    SelfControlOrInstinct getControlChoice();

    /**
     * Возвращает иерархию грехов для этого пути.
     * <p>
     * Иерархия представлена в виде списка грехов, отсортированных
     * от самого тяжёлого (ранг 1) до самого лёгкого (ранг 10).
     * <p>
     * При совершении проступка определённого ранга персонаж
     * рискует потерять пункты своего Пути (см. главу 7).
     *
     * @return список грехов, упорядоченный по рангу тяжести
     */
    List<EnlightenmentPathSin> getSinHierarchy();
}