package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.disciplines;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.disciplines.power.DisciplinePower;
import org.springframework.lang.Nullable;

import java.util.List;

/**
 * Интерфейс дисциплины вампира.
 * <p>
 * Дисциплина — это сверхъестественная способность, присущая вампирам.
 * Каждая дисциплина представляет собой дерево умений (сил),
 * доступных по мере увеличения уровня владения дисциплиной.
 * <p>
 * Дисциплины могут быть основными (например, Celerity, Potence)
 * или путями (например, Path of Blood внутри Thaumaturgy).
 * Пути являются отдельными дисциплинами со своей иерархией сил.
 * <p>
 * Реализации этого интерфейса являются синглтонами в контейнере Spring
 * и должны быть помечены аннотацией {@link org.springframework.stereotype.Component}.
 *
 * @see DisciplineFactory
 * @see DisciplinePower
 * @see com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.VampireCharacter
 */
public interface Discipline {

    /**
     * Возвращает уникальный строковый идентификатор дисциплины.
     * <p>
     * Используется для хранения в базе данных (как ключ в мапе уровней)
     * и для получения конкретной реализации через {@link DisciplineFactory}.
     *
     * @return уникальный строковый идентификатор
     */
    String getId();

    /**
     * Возвращает отображаемое имя дисциплины для пользовательского интерфейса.
     *
     * @return человекочитаемое название дисциплины
     */
    String getDisplayName();

    /**
     * Возвращает полное описание дисциплины.
     * <p>
     * Описание должно содержать информацию о природе дисциплины,
     * её происхождении и основных принципах использования.
     *
     * @return подробное описание дисциплины
     */
    String getDescription();

    /**
     * Возвращает общие правила использования дисциплины.
     * <p>
     * Например, описание пассивных эффектов, базовой стоимости,
     * общих ограничений, которые применяются ко всем силам.
     * Может быть null, если таких правил нет.
     */
    @Nullable
    default String getGeneralRules() {
        return null;
    }

    /**
     * Определяет, является ли эта дисциплина путём (Path).
     * <p>
     * Пути — это специализированные дисциплины, которые обычно
     * являются частью более крупной дисциплины (например, Thaumaturgy).
     * Пути имеют собственные иерархии сил и развиваются независимо.
     *
     * @return true, если дисциплина является путём
     */
    default boolean isPath() {
        return false;
    }

    /**
     * Возвращает родительскую дисциплину для путей.
     * <p>
     * Если дисциплина является путём, этот метод возвращает
     * дисциплину, к которой этот путь относится.
     * Например, для "Пути Крови" родительской дисциплиной
     * будет "Тауматургия".
     *
     * @return родительская дисциплина, или null для основных дисциплин
     */
    default Discipline getParentDiscipline() {
        return null;
    }

    /**
     * Возвращает список всех сил, доступных в этой дисциплине.
     * <p>
     * Силы сгруппированы по уровням. Каждая сила имеет свой уровень,
     * название, описание и возможные параметры активации (стоимость,
     * характеристики для броска).
     *
     * @return список всех сил дисциплины
     */
    List<DisciplinePower> getPowers();

    /**
     * Возвращает список сил, доступных на указанном уровне.
     * <p>
     * Уровень определяется количеством вложенных пунктов в дисциплину.
     * Например, при уровне 3 доступны все силы с level <= 3.
     *
     * @param level уровень владения дисциплиной (1-5 и выше)
     * @return список сил, доступных на этом уровне
     */
    default List<DisciplinePower> getPowersForLevel(int level) {
        if (level <= 0) {
            return List.of();
        }
        return getPowers().stream()
                .filter(power -> power.getLevel() <= level)
                .toList();
    }

    /**
     * Проверяет, есть ли выбор между несколькими силами на данном уровне.
     * <p>
     * Для уровней 6+ часто существует выбор между несколькими
     * старшими силами. Этот метод помогает определить, нужно ли
     * предоставлять пользователю выбор при создании персонажа.
     *
     * @param level уровень владения дисциплиной
     * @return true, если на этом уровне есть выбор между силами
     */
    default boolean hasChoiceAtLevel(int level) {
        if (level <= 0) {
            return false;
        }
        List<DisciplinePower> powers = getPowers().stream()
                .filter(p -> p.getLevel() == level)
                .toList();
        return powers.size() > 1;
    }

    /**
     * Возвращает список кодов дисциплин, которые являются предварительными
     * условиями для изучения этой дисциплины (если есть).
     * <p>
     * Например, для изучения старших сил может потребоваться
     * определённый уровень владения базовой дисциплиной.
     *
     * @return список идентификаторов дисциплин-предварительных условий
     */
    default List<String> getPrerequisites() {
        return List.of();
    }
}