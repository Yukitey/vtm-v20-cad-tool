package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.backgrounds;

import org.springframework.stereotype.Component;

/**
 * Членство в Чёрной Руке (Black Hand Membership).
 * <p>
 * Доступно только вампирам Шабаша.
 * Персонаж — член знаменитой и ужасной Чёрной Руки, организации
 * фанатичных солдат и убийц на службе Шабаша.
 */
@Component
public class BlackHandMembershipBackground implements Background {

    public static final String ID = "BLACK_HAND_MEMBERSHIP";

    @Override
    public String getId() {
        return ID;
    }

    @Override
    public String getDisplayName() {
        return "Членство в Чёрной Руке";
    }

    @Override
    public String getDescription() {
        return """
                Доступно только вампирам Шабаша.
                
                Персонаж — член знаменитой и ужасной Чёрной Руки, организации
                фанатичных солдат и убийц на службе Шабаша. Наличие этого факта
                биографии означает, что персонаж является действительным членом
                этой группировки и обладает всеми сопутствующими обязанностями
                и привилегиями.
                
                1 пункт — Рядовой член Чёрной Руки; один раз на протяжении истории
                персонаж может позвать на помощь одного члена группировки.
                2 пункта — Уважаемый член Чёрной Руки; один раз на протяжении истории
                персонаж может позвать на помощь двух членов группировки.
                3 пункта — Прославленный член Чёрной Руки; один раз на протяжении
                истории персонаж может позвать на помощь пятерых членов группировки.
                4 пункта — Герой Чёрной Руки; два раза на протяжении истории персонаж
                может позвать на помощь семерых членов группировки (но будьте
                осмотрительнее — если они решат, что персонаж слишком слаб, чтобы
                справляться с трудностями самостоятельно, он может лишиться одного
                или даже нескольких пунктов членства).
                5 пунктов — Легенда Чёрной Руки; два раза на протяжении истории
                персонаж может позвать на помощь дюжину членов группировки.
                
                Членство в Чёрной Руке очень престижно, и сторонники Шабаша относятся
                к этой группировке с большим уважением. Если при общении со сторонниками
                этой фракции персонаж открыто идентифицирует себя как члена Чёрной Руки,
                он может прибавить значение членства к пулу любой социальной проверки
                вдобавок к значению статуса и других подходящих параметров.
                """;
    }
}