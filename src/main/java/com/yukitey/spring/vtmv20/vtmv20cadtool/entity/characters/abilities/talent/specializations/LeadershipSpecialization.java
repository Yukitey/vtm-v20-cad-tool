package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.talent.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для таланта Лидерство (Leadership).
 * Лидерство определяет способность персонажа вести за собой людей, организовывать их работу
 * и добиваться добровольного или вынужденного подчинения.
 */
@Getter
@AllArgsConstructor
public enum LeadershipSpecialization implements EnumSpecialization {

    /**
     * Риторика (Oratory).
     * Умение убеждать и вдохновлять большие группы людей своей речью.
     */
    ABL_TAL_LEA_ORATORY(
            "Риторика",
            "Вы — прирожденный оратор. Применяется, когда нужно произнести пламенную речь перед толпой или вдохновить своих последователей на решительные действия."),

    /**
     * Убеждение (Persuasion).
     * Способность логически и аргументированно склонять подчиненных к выполнению приказов.
     */
    ABL_TAL_LEA_PERSUASION(
            "Убеждение",
            "Вам не нужно кричать, чтобы вас слушали. Применяется для того, чтобы разъяснить цели и добиться осознанного выполнения ваших распоряжений."),

    /**
     * Дружелюбие (Friendly).
     * Стиль лидерства, основанный на симпатии и неформальном авторитете.
     */
    ABL_TAL_LEA_FRIENDLY(
            "Дружелюбие",
            "Вы — душа компании и лидер-друг. Применяется для поддержания высокого морального духа в группе и сплочения коллектива через личную привязанность."),

    /**
     * Открытость (Openness).
     * Честность и прозрачность в управлении, вызывающие доверие.
     */
    ABL_TAL_LEA_OPENNESS(
            "Открытость",
            "Вашим решениям доверяют, потому что вы ничего не скрываете. Применяется для создания атмосферы доверия и предотвращения интриг внутри вашей организации."),

    /**
     * Благородство (Noble).
     * Лидерство, основанное на чувстве долга, чести и высоком статусе.
     */
    ABL_TAL_LEA_NOBLE(
            "Благородство",
            "Вы ведете за собой примером собственного достоинства. Применяется в ситуациях, когда ваш авторитет опирается на ваше происхождение, кодекс чести или безупречную репутацию."),

    /**
     * Субординация (Military Hierarchy).
     * Навык управления в жестких структурах с четкой вертикалью власти.
     */
    ABL_TAL_LEA_SUBORDINATION(
            "Субординация",
            "Вы мастер дисциплины. Применяется для управления военизированными отрядами или структурами, где приказы не обсуждаются, а четко выполняются."),

    /**
     * СМИ (Media).
     * Способность руководить общественным мнением через информационные каналы.
     */
    ABL_TAL_LEA_MEDIA(
            "СМИ",
            "Ваше лидерство простирается за пределы личного общения. Применяется для управления массами через прессу, телевидение или интернет-платформы.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения специализации. */
    private final String description;
}