package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.skill.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для навыка Выживание (Survival).
 * Отражают способности выживать в дикой природе и ориентироваться в разных средах.
 */
@Getter
@AllArgsConstructor
public enum SurvivalSpecialization implements EnumSpecialization {

    /**
     * Чтение следов (Tracking).
     * Умение находить и интерпретировать следы людей и животных.
     */
    TRACKING("Чтение следов", "Вы видите невидимое. Применяется для выслеживания добычи, поиска пропавших или изучения местности."),

    /**
     * Леса (Forests).
     * Выживание и ориентирование в лесной местности.
     */
    FORESTS("Леса", "Вы знаете все секреты леса. Применяется для поиска пищи, воды, укрытия и навигации в лесных массивах."),

    /**
     * Джунгли (Jungles).
     * Специфика выживания в тропических лесах.
     */
    JUNGLES("Джунгли", "Вы адаптированы к влажному климату. Применяется для передвижения по джунглям, распознавания опасных растений и животных."),

    /**
     * Города (Cities).
     * Использование городской среды для укрытия, поиска пищи и ориентирования.
     */
    CITIES("Города", "Вы выживаете в каменных джунглях. Применяется для поиска убежища, провизии и перемещения по трущобам и промышленным зонам."),

    /**
     * Охота (Hunting).
     * Добыча пропитания в дикой природе (животные, рыба).
     */
    HUNTING("Охота", "Вы искусный охотник. Применяется для выслеживания и поимки дичи, а также для рыболовства.");

    private final String displayName;
    private final String description;
}