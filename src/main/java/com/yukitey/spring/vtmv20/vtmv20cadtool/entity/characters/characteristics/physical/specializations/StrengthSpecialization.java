package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.characteristics.physical.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для характеристики Сила (Strength).
 * Определяют конкретные области физического превосходства персонажа.
 */
@Getter
@AllArgsConstructor
public enum StrengthSpecialization implements EnumSpecialization {

    /**
     * Мертвая хватка (Dead Grip).
     * Персонаж обладает невероятной силой кистей и предплечий.
     */
    STR_DEAD_GRIP(
            "Мертвая хватка",
            "Ваши пальцы подобны стальным тискам. Применяется при попытках удержать противника в захвате, взобраться по отвесной стене или не выпустить предмет из рук."),

    /**
     * Мощные ручищи (Massive Arms).
     * Непропорционально развитая мускулатура верхнего плечевого пояса.
     */
    STR_MASSIVE_ARMS(
            "Мощные ручищи",
            "Ваши руки огромны и сильны. Применяется для поднятия или перемещения массивных объектов, а также при нанесении сокрушительных ударов в ближнем бою."),

    /**
     * Второе дыхание (Second Wind).
     * Способность мобилизовать все силы организма в критический момент.
     */
    STR_SECOND_WIND(
            "Второе дыхание",
            "Вы способны на кратковременный рывок за пределы своих возможностей. Применяется, когда требуется совершить одно решающее силовое усилие на пределе сил."),

    /**
     * Грозный вид (Intimidating Bulk).
     * Физическая мощь персонажа настолько очевидна, что внушает трепет.
     */
    STR_FORMIDABLE_LOOK(
            "Грозный вид",
            "Ваша физическая мощь говорит сама за себя. Может применяться в силовых методах воздействия, где размер и гора мышц имеют решающее значение для успеха.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения. */
    private final String description;
}