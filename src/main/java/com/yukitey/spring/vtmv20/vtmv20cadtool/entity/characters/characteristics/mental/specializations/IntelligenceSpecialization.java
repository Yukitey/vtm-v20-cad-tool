package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.characteristics.mental.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для характеристики Интеллект (Intelligence).
 * Интеллект определяет способность персонажа к обучению, анализу,
 * запоминанию информации и решению сложных логических задач.
 */
@Getter
@AllArgsConstructor
public enum IntelligenceSpecialization implements EnumSpecialization {

    /**
     * Начитанность (Well-Read).
     * Огромный багаж знаний, почерпнутый из книг и различных источников.
     */
    INT_WELL_READ(
            "Начитанность",
            "Ваша эрудиция не знает границ. Применяется, когда нужно вспомнить редкий факт, сослаться на исторический прецедент или найти информацию в архивах."),

    /**
     * Творческий подход (Creative).
     * Способность находить нестандартные и оригинальные пути решения проблем.
     */
    INT_CREATIVE(
            "Творческий подход",
            "Вы мыслите вне рамок. Применяется при разработке новых теорий, создании произведений искусства или когда обычные методы решения задачи заходят в тупик."),

    /**
     * Аналитика (Analytical).
     * Умение разбивать сложную информацию на составляющие части и видеть взаимосвязи.
     */
    INT_ANALYTICAL(
            "Аналитика",
            "Вы видите закономерности там, где другие видят хаос. Применяется для расшифровки кодов, финансового анализа или понимания сложных стратегий оппонента."),

    /**
     * Решение задач (Problem-Solving).
     * Практический интеллект, направленный на поиск выхода из конкретных затруднений.
     */
    INT_PROBLEM_SOLVING(
            "Решение задач",
            "Вы мастер дедукции и логики. Применяется для быстрого поиска выхода из критических ситуаций, требующих интеллектуального напряжения."),

    /**
     * Систематика (Systematic).
     * Способность эффективно организовывать информацию и процессы.
     */
    INT_SYSTEMATIC(
            "Систематика",
            "У вас структурированный ум. Применяется при планировании долгосрочных операций, управлении большими массивами данных или систематизации знаний.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения. */
    private final String description;
}