package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.talent.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для таланта Запугивание (Intimidation).
 * Отражают методы, которыми персонаж подавляет чужую волю, внушает страх
 * или заставляет окружающих действовать в своих интересах под давлением.
 */
@Getter
@AllArgsConstructor
public enum IntimidationSpecialization implements EnumSpecialization {

    /**
     * Завуалированные угрозы (Veiled Threats).
     * Умение намекать на ужасные последствия, сохраняя внешнее спокойствие.
     */
    ABL_TAL_INT_VEILED_THREATS(
            "Завуалированные угрозы",
            "Вы пугаете своей вежливостью. Применяется, когда нужно донести до собеседника опасность его положения, не прибегая к открытой агрессии, что особенно ценится в Элизиумах."),

    /**
     * Злоупотребление властью (Authority).
     * Использование своего статуса, должности или ранга как рычага давления.
     */
    ABL_TAL_INT_AUTHORITY_ABUSE(
            "Злоупотребление властью",
            "Вы давите своим положением. Применяется, когда вы напоминаете подчиненным или младшим Сородичам об их обязанностях и своей власти карать за их невыполнение."),

    /**
     * Физическое принуждение (Physical Coercion).
     * Демонстрация силы или непосредственная угроза физической расправы.
     */
    ABL_TAL_INT_PHYSICAL_COERCION(
            "Физическое принуждение",
            "Ваша мощь — ваш главный аргумент. Применяется при нависании над жертвой, демонстрации оружия или в ситуациях, где физическое превосходство очевидно."),

    /**
     * Шантаж (Blackmail).
     * Давление на персонажа через его секреты, грехи или близких.
     */
    ABL_TAL_INT_BLACKMAIL(
            "Шантаж",
            "Вы знаете, на что нажать. Применяется, когда вы используете компрометирующую информацию или угрозу раскрытия тайны, чтобы заставить цель подчиниться."),

    /**
     * Травля (Browbeating).
     * Постоянное психологическое давление и словесные нападки.
     */
    ABL_TAL_INT_BROWBEATING(
            "Травля",
            "Вы буквально забиваете оппонента словами и агрессией. Применяется для того, чтобы морально сломить человека, заставить его чувствовать себя ничтожным и беззащитным.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения специализации. */
    private final String description;
}