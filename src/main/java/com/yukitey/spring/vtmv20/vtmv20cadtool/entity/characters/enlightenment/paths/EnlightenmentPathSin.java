package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.enlightenment.paths;

import lombok.Builder;
import lombok.Data;

/**
 * Описание одного греха в иерархии Пути Просветления.
 * <p>
 * Каждый Путь имеет свою иерархию грехов — шкалу от 1 до 10,
 * где 1 — самый тяжёлый, непростительный грех,
 * а 10 — самый лёгкий проступок.
 * При совершении поступка, соответствующего определённому уровню,
 * персонаж рискует потерять пункт своего Пути.
 * <p>
 * См. главу 7 «Мораль» в книге правил V20.
 */
@Data
@Builder
public class EnlightenmentPathSin {

    /**
     * Ранг тяжести греха.
     * <p>
     * Диапазон: от 1 до 10.
     * 1 — самый тяжёлый грех (например, диаблери, массовые убийства),
     * 10 — самый лёгкий (например, эгоистичные мысли).
     * <p>
     * Чем ниже значение, тем быстрее падает показатель Пути
     * при совершении такого проступка.
     */
    private int gravityRank;

    /**
     * Краткое описание греха.
     * <p>
     * Например: "Умышленное убийство невинного", "Воровство",
     * "Отказ помочь товарищу" и т.д.
     */
    private String description;

    /**
     * Конкретный пример или пояснение, иллюстрирующее данный грех.
     * <p>
     * Помогает игрокам и рассказчику правильно интерпретировать,
     * что именно считается проступком этого уровня.
     * Например: "Украсть у смертного кошелёк" для ранга 7.
     */
    private String example;
}