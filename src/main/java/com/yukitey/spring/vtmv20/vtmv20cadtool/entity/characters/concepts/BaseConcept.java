package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.concepts;


import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Базовые амплуа (концепции) из основной книги правил V20.
 */
@Getter
@AllArgsConstructor
public enum BaseConcept implements Concept {

    /**
     * Артист — созидатель.
     */
    ARTIST("Артист", "Созидатель, ищущий новые пути самовыражения или эстетического восприятия мира."),

    /**
     * Боец — человек действия.
     */
    WARRIOR("Боец", "Тот, кто привык решать конфликты силой, будь то на войне или на улице."),

    /**
     * Бродяга — человек без корней.
     */
    DRIFTER("Бродяга", "Человек без корней, который всегда в движении и не желает связывать себя обязательствами."),

    /**
     * Изгой — вне рамок общества.
     */
    OUTSIDER("Изгой", "Тот, кто стоит по ту сторону общественных норм или был изгнан из привычной среды."),

    /**
     * Интеллектуал — человек мысли.
     */
    INTELLECTUAL("Интеллектуал", "Личность, полагающаяся на логику, знания и силу своего разума."),

    /**
     * Неформал — представитель субкультуры.
     */
    BOHEMIAN("Неформал", "Индивидуалист, отвергающий мейнстрим и живущий по правилам своей группы."),

    /**
     * Подросток — молодой и неопытный.
     */
    KID("Подросток", "Молодой и часто наивный персонаж, только начинающий познавать мир."),

    /**
     * Политик — жаждущий власти.
     */
    POLITICIAN("Политик", "Тот, кто умеет управлять людьми и стремится занять место в иерархии власти."),

    /**
     * Преступник — живущий вне закона.
     */
    CRIMINAL("Преступник", "Человек, нарушающий закон ради выживания, наживы или по идейным соображениям."),

    /**
     * Профессионал — квалифицированный специалист.
     */
    PROFESSIONAL("Профессионал", "Специалист, чья жизнь и личность тесно связаны с его карьерой и навыками."),

    /**
     * Работяга — человек труда.
     */
    WORKING_CLASS("Работяга", "Простой труженик, составляющий костяк общества и привыкший к тяжелому труду."),

    /**
     * Репортер — искатель информации.
     */
    REPORTER("Репортер", "Искатель сенсаций или правды, чья цель — раскрывать секреты и доносить их до других."),

    /**
     * Светский лев — звезда общества.
     */
    SOCIALITE("Светский лев", "Человек, который чувствует себя как рыба в воде в высшем обществе."),

    /**
     * Сыщик — искатель скрытых фактов.
     */
    INVESTIGATOR("Сыщик", "Внимательный наблюдатель, способный распутать самое сложное дело.");

    private final String displayName;
    private final String description;
}