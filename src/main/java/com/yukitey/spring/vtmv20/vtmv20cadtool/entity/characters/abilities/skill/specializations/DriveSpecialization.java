package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.skill.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для навыка Вождение (Drive).
 * Определяют типы транспортных средств и ситуации вождения, в которых персонаж особенно искусен.
 */
@Getter
@AllArgsConstructor
public enum DriveSpecialization implements EnumSpecialization {

    /**
     * Автомобили (Cars).
     * Управление легковыми автомобилями, включая спортивные и представительские модели.
     */
    CARS("Автомобили", "Вы уверенно чувствуете себя за рулём любого легкового автомобиля. Применяется для обычной езды, парковки и базовых манёвров."),

    /**
     * Мотоциклы (Motorcycles).
     * Управление мотоциклами различных классов.
     */
    MOTORCYCLES("Мотоциклы", "Вы мастерски управляете мотоциклом. Применяется для скоростной езды, манёвров в потоке и преодоления бездорожья."),

    /**
     * Гонки (Racing).
     * Профессиональные навыки участия в гонках и скоростного вождения.
     */
    RACING("Гонки", "Вы знаете все тонкости гоночного вождения. Применяется для обгонов, входа в повороты на высокой скорости и пилотирования на треке."),

    /**
     * Езда по городу (Urban Driving).
     * Маневрирование в плотном городском трафике.
     */
    URBAN_DRIVING("Езда по городу", "Вы легко ориентируетесь в городских пробках. Применяется для агрессивного вождения, ухода от преследования и проезда в ограниченных пространствах."),

    /**
     * Уход от погонь (Escape Driving).
     * Специфические техники для отрыва от преследователей.
     */
    ESCAPE_DRIVING("Уход от погонь", "Вы знаете, как затеряться в потоке. Применяется для ухода от полиции или других преследователей с использованием контраварийных приёмов.");

    private final String displayName;
    private final String description;
}