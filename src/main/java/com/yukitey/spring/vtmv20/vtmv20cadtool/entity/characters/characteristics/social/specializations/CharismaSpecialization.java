package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.characteristics.social.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для характеристики Обаяние (Charisma).
 * Обаяние отражает врожденную способность персонажа вызывать симпатию и вести за собой,
 * опираясь на личный магнетизм и манеру общения.
 */
@Getter
@AllArgsConstructor
public enum CharismaSpecialization implements EnumSpecialization {

    /**
     * Изящество (Graceful).
     * Способность держаться достойно и благородно в любой ситуации.
     */
    CHA_GRACEFUL(
            "Изящество",
            "Ваши манеры безупречны. Применяется, когда нужно произвести впечатление благородством или сохранить лицо в высшем обществе."),

    /**
     * Лесть (Flattery).
     * Умение говорить людям то, что они хотят услышать, для достижения своих целей.
     */
    CHA_FLATTERY(
            "Лесть",
            "Вы мастерски находите путь к сердцу через комплименты. Применяется для того, чтобы расположить к себе эгоцентричных или властных личностей."),

    /**
     * Напористость (Forceful).
     * Способность подавлять чужую волю силой своего авторитета и убежденности.
     */
    CHA_FORCEFUL(
            "Напористость",
            "Ваше присутствие невозможно игнорировать. Применяется, когда нужно перехватить инициативу в разговоре или заставить других следовать вашему примеру."),

    /**
     * Вежливость (Courteous).
     * Безупречное знание этикета и умение быть тактичным.
     */
    CHA_COURTEOUS(
            "Вежливость",
            "Вы — эталон такта. Применяется для того, чтобы сгладить углы в конфликте или выразить почтение высокопоставленным Сородичам."),

    /**
     * Остроумие (Witty).
     * Умение быстро находить меткие и забавные ответы.
     */
    CHA_WITTY(
            "Остроумие",
            "Ваш язык остер, а шутки всегда своевременны. Применяется для завоевания популярности на вечеринках или чтобы элегантно осадить оппонента."),

    /**
     * Выразительность (Eloquent).
     * Способность ярко и доходчиво доносить свои мысли и чувства.
     */
    CHA_ELOQUENT(
            "Выразительность",
            "Вы говорите страстно и убедительно. Применяется при чтении речей, выступлении перед аудиторией или когда нужно зажечь огонь в сердцах слушателей."),

    /**
     * Прямота (Direct).
     * Манера общения, подкупающая своей честностью и отсутствием двойного дна.
     */
    CHA_DIRECT(
            "Прямота",
            "Вы говорите то, что думаете, и это внушает доверие. Применяется, когда нужно убедить собеседника в своей искренности и серьезности намерений.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения. */
    private final String description;
}