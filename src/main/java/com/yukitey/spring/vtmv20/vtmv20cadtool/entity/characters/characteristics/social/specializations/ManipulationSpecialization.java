package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.characteristics.social.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для характеристики Манипуляция (Manipulation).
 * Манипуляция определяет способность персонажа заставлять других делать то,
 * что он хочет, часто так, что они этого даже не замечают.
 */
@Getter
@AllArgsConstructor
public enum ManipulationSpecialization implements EnumSpecialization {

    /**
     * Убеждение (Persuasive).
     * Способность подбирать неоспоримые доводы и логические цепочки.
     */
    MAN_PERSUASIVE(
            "Убеждение",
            "Вы мастерски ведете спор, заставляя окружающих принимать вашу точку зрения как единственно верную. Применяется, когда нужно логически обосновать свою позицию."),

    /**
     * Соблазнение (Seductive).
     * Умение играть на желаниях и слабостях других для достижения целей.
     */
    MAN_SEDUCTIVE(
            "Соблазнение",
            "Вы знаете, как очаровать и затуманить разум. Применяется для установления доверительных отношений или получения выгоды через личное обаяние и страсть."),

    /**
     * Здравый смысл (Reasonable).
     * Манера общения, которая заставляет любые слова звучать рационально.
     */
    MAN_REASONABLE(
            "Здравый смысл",
            "Ваши слова всегда звучат как голос разума. Применяется, чтобы успокоить оппонента или придать своим требованиям вид логической необходимости."),

    /**
     * Отвлечение внимания (Red Herring).
     * Мастерство уводить разговор в сторону от неудобных тем.
     */
    MAN_RED_HERRING(
            "Отвлечение внимания",
            "Вы мастерски переводите тему, когда почва уходит из-под ног. Применяется, чтобы скрыть важную информацию или запутать преследователя в споре."),

    /**
     * Искажение фактов (Misdirection).
     * Умение подтасовывать информацию, сохраняя видимость правды.
     */
    MAN_MISDIRECTION(
            "Искажение фактов",
            "Вы умеете подавать ложь в обертке из полуправды. Применяется при попытках оправдаться, создать ложное алиби или дискредитировать кого-либо.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения. */
    private final String description;
}