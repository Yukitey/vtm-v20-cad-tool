package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.skill.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для навыка Обращение с животными (Animal Ken).
 * Отражают мастерство взаимодействия с разными видами животных.
 */
@Getter
@AllArgsConstructor
public enum AnimalKenSpecialization implements EnumSpecialization {

    /**
     * Собаки (Dogs).
     * Дрессировка и понимание собак.
     */
    DOGS("Собаки", "Вы легко находите общий язык с собаками. Применяется для дрессировки, успокоения или работы со служебными собаками."),

    /**
     * Лошади (Horses).
     * Обращение с лошадьми, верховая езда и уход.
     */
    HORSES("Лошади", "Вы чувствуете лошадь как себя. Применяется для верховой езды, тренировок и работы в конюшне."),

    /**
     * Хищные птицы (Birds of Prey).
     * Дрессировка соколов, ястребов и других хищных птиц.
     */
    BIRDS_OF_PREY("Хищные птицы", "Вы мастер соколиной охоты. Применяется для дрессировки, использования птиц в охоте и их содержания."),

    /**
     * Дрессировка (Training).
     * Общие принципы обучения любых животных командам.
     */
    TRAINING_ANIMAL("Дрессировка", "Вы способны научить любое животное основным командам. Применяется для дрессировки зверей цирка, домашних питомцев или служебных собак."),

    /**
     * Дикие животные (Wild Animals).
     * Понимание поведения диких зверей и способность взаимодействовать с ними.
     */
    WILD_ANIMALS("Дикие животные", "Вы знаете язык дикой природы. Применяется для успокоения животных в зоопарке, приручения или отпугивания хищников.");

    private final String displayName;
    private final String description;
}