package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.skill.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для навыка Воровство (Larceny).
 * Отражают специализацию в различных аспектах криминальной деятельности: взлом, кражи, угоны.
 */
@Getter
@AllArgsConstructor
public enum LarcenySpecialization implements EnumSpecialization {

    /**
     * Сейфы (Safes).
     * Навык взлома сейфов и хранилищ.
     */
    SAFES("Сейфы", "Вы легко находите слабые места в замках сейфов. Применяется для вскрытия механических и электронных замков, включая комбинированные кодовые замки."),

    /**
     * Замки (Locks).
     * Мастерство открывания замков любого типа, кроме сейфов.
     */
    LOCKS("Замки", "Вы способны открыть любой дверной замок или навесной замок. Применяется для проникновения в помещения через двери."),

    /**
     * Угон (Hotwiring).
     * Запуск двигателя без ключа и угон транспортных средств.
     */
    HOTWIRING("Угон", "Вы легко можете завести любой автомобиль без ключа. Применяется для угона или быстрого использования чужого транспорта."),

    /**
     * Карманные кражи (Pickpocketing).
     * Ловкость рук для изъятия вещей у жертвы незаметно.
     */
    PICKPOCKETING("Карманные кражи", "Вы способны стащить кошелёк или часы, не привлекая внимания. Применяется в толпе или при непосредственном контакте с жертвой."),

    /**
     * Снятие отпечатков (Trails).
     * Умение заметать следы и обходить сигнализации.
     */
    TRAILS("Снятие отпечатков", "Вы знаете, как не оставлять следов. Применяется для обхода датчиков движения, систем видеонаблюдения и других мер безопасности.");

    private final String displayName;
    private final String description;
}