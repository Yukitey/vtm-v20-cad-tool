package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.characteristics.mental.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для характеристики Смекалка (Wits).
 * Смекалка отражает быстроту реакции персонажа, его сообразительность в стрессовых ситуациях
 * и способность мгновенно принимать решения, когда нет времени на раздумья.
 */
@Getter
@AllArgsConstructor
public enum WitsSpecialization implements EnumSpecialization {

    /**
     * Деловая хватка (Business Savvy).
     * Способность мгновенно видеть выгоду и ориентироваться в рыночных или бюрократических хитросплетениях.
     */
    WIT_BUSINESS_SAVVY(
            "Деловая хватка",
            "Вы мгновенно оцениваете прибыльность ситуации. Применяется при быстрых сделках, оценке рисков на лету или когда нужно не упустить мимолетную финансовую возможность."),

    /**
     * Подвешенный язык (Fast Talk).
     * Умение быстро и уверенно говорить, сбивая оппонента с толку или забалтывая его.
     */
    WIT_FAST_TALK(
            "Подвешенный язык",
            "Вы способны заговорить зубы кому угодно. Применяется, когда нужно быстро оправдаться перед полицией, отвлечь охранника или запутать собеседника потоком слов."),

    /**
     * Импровизация (Improvisation).
     * Талант находить применение подручным средствам и менять планы на ходу.
     */
    WIT_IMPROVISATION(
            "Импровизация",
            "Вы никогда не заходите в тупик. Применяется, когда изначальный план провалился и нужно мгновенно придумать альтернативу, используя то, что есть под рукой."),

    /**
     * Засады (Ambushes).
     * Мастерство в организации внезапных нападений и умение не попадать в них самому.
     */
    WIT_AMBUSHES(
            "Засады",
            "Вы чувствуете ловушки и знаете, как их расставлять. Применяется при подготовке внезапных атак или в бросках на то, чтобы не оказаться застигнутым врасплох.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения. */
    private final String description;
}