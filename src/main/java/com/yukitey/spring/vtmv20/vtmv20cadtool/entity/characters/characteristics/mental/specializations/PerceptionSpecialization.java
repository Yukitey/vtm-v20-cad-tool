package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.characteristics.mental.specializations;
import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для характеристики Восприятие (Perception).
 * Восприятие определяет способность персонажа замечать детали,
 * чувствовать изменения в окружении и распознавать скрытые угрозы.
 */
@Getter
@AllArgsConstructor
public enum PerceptionSpecialization implements EnumSpecialization {

    /**
     * Внимательность (Attentive).
     * Способность замечать мелкие и незначительные на первый взгляд детали.
     */
    PER_ATTENTIVE(
            "Внимательность",
            "Вы ничего не упускаете из виду. Применяется при поиске улик, скрытых предметов или когда нужно заметить малейшие изменения в привычной обстановке."),

    /**
     * Проницательность (Insightful).
     * Умение видеть истинные мотивы и чувства за внешней маской собеседника.
     */
    PER_INSIGHTFUL(
            "Проницательность",
            "Вы видите людей насквозь. Применяется для распознавания лжи, понимания истинных эмоций или предсказания действий оппонента в социальном взаимодействии."),

    /**
     * Осторожность (Wary).
     * Постоянная бдительность и ожидание опасности.
     */
    PER_WARY(
            "Осторожность",
            "Вас трудно застать врасплох. Применяется для обнаружения засад, слежки или чувства того, что за вами кто-то наблюдает."),

    /**
     * Распознавание (Discernment).
     * Способность отличать одни объекты или явления от других в сложных условиях.
     */
    PER_DISCERNMENT(
            "Распознавание",
            "Вы умеете отделять зерна от плевел. Применяется для опознания конкретных личностей в толпе, идентификации звуков или запахов в зашумленной среде."),

    /**
     * Тактика (Tactical).
     * Умение мгновенно оценивать обстановку с точки зрения боя или стратегии.
     */
    PER_TACTICAL(
            "Тактика",
            "Вы видите поле боя как шахматную доску. Применяется для оценки сильных и слабых позиций, поиска укрытий и быстрого анализа боевой ситуации.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения. */
    private final String description;
}