package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.abilities.talent.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для таланта Шестое чувство (Awareness).
 * Отражают чувствительность персонажа к мистическим энергиям, сверхъестественным проявлениям
 * и его способность интуитивно распознавать присутствие иных сил.
 */
@Getter
@AllArgsConstructor
public enum AwarenessSpecialization implements EnumSpecialization {

    /**
     * Призрачная активность (Ghostly Activity).
     * Способность чувствовать присутствие обитателей Подземного Мира (Wraiths).
     */
    ABL_TAL_AWA_GHOSTLY_ACTIVITY(
            "Призрачная активность",
            "Вы чувствуете холод смерти и присутствие бесплотных духов. Применяется для обнаружения призраков, определения мест с истонченной Завесой или ощущения следов некромантии."),

    /**
     * Мистические артефакты (Mystical Artifacts).
     * Чутье на предметы, наделенные сверхъестественной силой.
     */
    ABL_TAL_AWA_MYSTICAL_ARTIFACTS(
            "Мистические артефакты",
            "Вы чувствуете «гул» магических предметов. Применяется для поиска артефактов, определения того, является ли вещь проклятой или зачарованной, и ощущения остаточной магии на объектах."),

    /**
     * Голоса в голове (Voices in the Head).
     * Использование внутреннего ментального шума как индикатора чужого присутствия.
     */
    ABL_TAL_AWA_VOICES_IN_HEAD(
            "Голоса в голове",
            "Ваша интуиция граничит с безумием. Применяется, когда ваши внутренние ощущения или «голоса» предупреждают вас о невидимой угрозе, телепатических контактах или ментальном воздействии."),

    /**
     * Разоблачение шарлатанов (Exposing Frauds).
     * Умение отличить истинную мистику от дешевых трюков и иллюзий.
     */
    ABL_TAL_AWA_EXPOSING_FRAUDS(
            "Разоблачение шарлатанов",
            "Вы видите разницу между магией и фокусами. Применяется для разоблачения фальшивых медиумов, иллюзионистов или тех, кто пытается имитировать сверхъестественные способности.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения специализации. */
    private final String description;
}