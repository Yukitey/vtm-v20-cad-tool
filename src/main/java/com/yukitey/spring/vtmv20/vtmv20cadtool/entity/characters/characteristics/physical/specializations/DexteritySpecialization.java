package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.characteristics.physical.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для характеристики Ловкость (Dexterity).
 * Отражают мастерство владения телом, координацию и скорость отклика.
 */
@Getter
@AllArgsConstructor
public enum DexteritySpecialization implements EnumSpecialization {

    /**
     * Точность (Precision).
     * Способность совершать выверенные и тонкие движения.
     */
    DEX_PRECISION(
            "Точность",
            "Ваши движения выверены до миллиметра. Применяется при стрельбе, выполнении тонкой ручной работы или нанесении ударов в уязвимые точки."),

    /**
     * Быстрота (Swiftness).
     * Общая скорость выполнения физических действий.
     */
    DEX_SWIFTNESS(
            "Быстрота",
            "Вы двигаетесь быстрее, чем успевает заметить глаз. Применяется, когда важнее совершить действие за минимальное время, например, при быстром извлечении оружия."),

    /**
     * Кошачья грация (Catlike Grace).
     * Естественная текучесть движений и безупречное чувство равновесия.
     */
    DEX_CATLIKE_GRACE(
            "Кошачья грация",
            "Вы всегда приземляетесь на лапы. Применяется при акробатических трюках, сохранении баланса на узких поверхностях и бесшумном перемещении."),

    /**
     * Молниеносная реакция (Lightning Reflexes).
     * Способность мгновенно реагировать на внешние раздражители.
     */
    DEX_LIGHTNING_REFLEXES(
            "Молниеносная реакция",
            "Ваше тело реагирует раньше, чем разум осознает угрозу. Применяется для перехвата летящих предметов, уклонения от внезапных атак или в бросках на инициативу.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения. */
    private final String description;
}