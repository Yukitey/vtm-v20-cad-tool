package com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.characteristics.physical.specializations;

import com.yukitey.spring.vtmv20.vtmv20cadtool.entity.characters.EnumSpecialization;
import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Специализации для характеристики Выносливость (Stamina).
 * Отражают физическую стойкость, жизненную силу и способность персонажа сопротивляться лишениям.
 */
@Getter
@AllArgsConstructor
public enum StaminaSpecialization implements EnumSpecialization {

    /**
     * Неутомимость (Tireless).
     * Способность выдерживать длительные нагрузки без признаков усталости.
     */
    STA_TIRELESS(
            "Неутомимость",
            "Вы способны часами продолжать физический труд или бег. Применяется при изматывающих переходах, длительных погонях и марафонах."),

    /**
     * Твердость (Toughness).
     * Физическая плотность и общая сопротивляемость урону.
     */
    STA_TOUGHNESS(
            "Твердость",
            "Вас трудно ранить или оглушить. Применяется при поглощении урона (soak), сопротивлении ядам или воздействию неблагоприятной среды."),

    /**
     * Несгибаемость (Unbending).
     * Ментально-физическая стойкость под давлением обстоятельств или боли.
     */
    STA_UNBENDING(
            "Несгибаемость",
            "Вы игнорируете попытки сломить вашу волю через физическое изнурение. Применяется при пытках или попытках заставить вас отступить из-за ран."),

    /**
     * Энергичность (Vigor).
     * Высокий внутренний тонус и способность к быстрой мобилизации сил.
     */
    STA_VIGOR(
            "Энергичность",
            "Вы всегда полны сил и готовы к действию. Применяется для быстрого восстановления после нагрузок или для поддержания активности в условиях крайнего истощения.");

    /** Локализованное название специализации. */
    private final String displayName;

    /** Подробное описание игровых ситуаций применения. */
    private final String description;
}